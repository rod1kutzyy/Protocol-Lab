"""Run the real GUI workflow in two migrated, disposable PostgreSQL schemas."""

import os
import subprocess
import tempfile
from pathlib import Path
from uuid import uuid4

from sqlalchemy import create_engine, text
from sqlalchemy.engine import make_url

ROOT = Path(__file__).resolve().parents[1]


def main():
    database = os.environ.get("PROTOCOL_LAB_TEST_DATABASE_URL")
    if not database:
        raise SystemExit(
            "Set PROTOCOL_LAB_TEST_DATABASE_URL to a local test PostgreSQL"
        )
    if make_url(database).host not in {"127.0.0.1", "localhost", "::1"}:
        raise SystemExit("E2E accepts a localhost test DB only")
    admin = create_engine(database)
    schemas = ["pl_e2e_" + uuid4().hex for _ in range(2)]
    try:
        urls = []
        for schema in schemas:
            with admin.begin() as conn:
                conn.execute(text(f'CREATE SCHEMA "{schema}"'))
            url = make_url(database).update_query_dict(
                {"options": f"-csearch_path={schema}"}
            )
            urls.append(url.render_as_string(hide_password=False))
            subprocess.run(
                [str(ROOT / "backend/.venv/bin/alembic"), "upgrade", "head"],
                cwd=ROOT / "backend",
                env={**os.environ, "PROTOCOL_LAB_DATABASE_URL": urls[-1]},
                check=True,
            )
        with tempfile.TemporaryDirectory(prefix="protocol-lab-e2e-") as temporary:
            env = {
                **os.environ,
                "PROTOCOL_LAB_E2E_DATABASE_URL": urls[0],
                "PROTOCOL_LAB_E2E_RESTORE_DATABASE_URL": urls[1],
                "PROTOCOL_LAB_E2E_ROOT": str(Path(temporary) / "source"),
                "PROTOCOL_LAB_E2E_RESTORE_ROOT": str(Path(temporary) / "destination"),
            }
            return subprocess.run(
                ["npm", "run", "test:e2e"], cwd=ROOT / "frontend", env=env, check=False
            ).returncode
    finally:
        for schema in schemas:
            with admin.begin() as conn:
                # Names are generated by this runner; no user's schema is dropped.
                conn.execute(text(f'DROP SCHEMA IF EXISTS "{schema}" CASCADE'))
        admin.dispose()


if __name__ == "__main__":
    raise SystemExit(main())
